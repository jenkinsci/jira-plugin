#!/usr/bin/env node
/*
 * Regenerates the trimmed Jira Cloud platform OpenAPI spec used by
 * hudson.plugins.jira.wiremock.OpenApiSpecConformance.
 *
 * The upstream spec is ~2.3 MB and was previously downloaded on every `mvn test`, which made
 * the "offline" WireMock suite depend on the network (see issue #248). We keep only the paths
 * the contract tests actually validate, plus every component they reference transitively.
 *
 * Usage:  node tools/trim-jira-openapi-spec.mjs
 *
 * The set of paths below must stay in sync with the OpenApiSpecConformance.assertConformsToSpec
 * call sites in JiraRestServiceWireMockTest. OpenApiSpecConformance fails loudly when a test
 * validates a path this file does not list, so a missing entry cannot silently disable checking.
 */

import { writeFileSync } from "node:fs";

const SPEC_URL = "https://developer.atlassian.com/cloud/jira/platform/swagger-v3.v3.json";
const OUTPUT = new URL(
    "../src/test/resources/hudson/plugins/jira/wiremock/jira-cloud-platform-openapi-trimmed.json",
    import.meta.url,
);

const KEPT_PATHS = [
    "/rest/api/3/issue/{issueIdOrKey}",
    "/rest/api/3/serverInfo",
    "/rest/api/3/version",
    "/rest/api/3/version/{id}",
    "/rest/api/3/project/{projectIdOrKey}",
    "/rest/api/3/project/{projectIdOrKey}/versions",
];

const spec = await (await fetch(SPEC_URL)).json();

const missing = KEPT_PATHS.filter((p) => !spec.paths[p]);
if (missing.length > 0) {
    throw new Error(`upstream spec no longer defines: ${missing.join(", ")}`);
}

const paths = Object.fromEntries(KEPT_PATHS.map((p) => [p, spec.paths[p]]));

// Walk every $ref reachable from the kept paths and pull the referenced components across,
// repeating until the closure stops growing (components reference other components).
const kept = {};
const seen = new Set();
const queue = [];

const collectRefs = (node) => {
    if (node === null || typeof node !== "object") {
        return;
    }
    if (Array.isArray(node)) {
        node.forEach(collectRefs);
        return;
    }
    for (const [key, value] of Object.entries(node)) {
        if (key === "$ref" && typeof value === "string" && value.startsWith("#/components/")) {
            if (!seen.has(value)) {
                seen.add(value);
                queue.push(value);
            }
        } else {
            collectRefs(value);
        }
    }
};

collectRefs(paths);

while (queue.length > 0) {
    const ref = queue.shift();
    const [, , section, name] = ref.split("/");
    const target = spec.components?.[section]?.[name];
    if (target === undefined) {
        throw new Error(`spec references ${ref}, which it does not define`);
    }
    (kept[section] ??= {})[name] = target;
    collectRefs(target);
}

// Security schemes are referenced by name from `security`, not by $ref, so copy them wholesale.
if (spec.components?.securitySchemes) {
    kept.securitySchemes = spec.components.securitySchemes;
}

const trimmed = {
    openapi: spec.openapi,
    info: {
        ...spec.info,
        description:
            `Trimmed copy of ${SPEC_URL}, generated by tools/trim-jira-openapi-spec.mjs. ` +
            "Contains only the paths hudson.plugins.jira.wiremock.JiraRestServiceWireMockTest " +
            "validates against, plus their transitively referenced components. Do not edit by hand.",
    },
    servers: spec.servers,
    security: spec.security,
    paths,
    components: kept,
};

writeFileSync(OUTPUT, JSON.stringify(trimmed, null, 2) + "\n");

const sections = Object.entries(kept)
    .map(([section, entries]) => `${section}=${Object.keys(entries).length}`)
    .join(" ");
console.log(`wrote ${OUTPUT.pathname}`);
console.log(`paths=${KEPT_PATHS.length} ${sections}`);
